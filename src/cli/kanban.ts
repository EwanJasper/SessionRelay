// ───────────────────── 结构化待办 → 看板（2026-10-15 夜 · B1） ─────────────────────
//
// 为什么：看板段的本来目的是「计划/下一步」——b3 实测这是全库最大盲区（只捕获 3.3%）。
// 而 ZCode 的 `todo` 表里**躺着真任务、真状态**（实测：主库 2059 条 / 进行中 187；
// music 622 / 24；内容形如「渲染管线换 GeckoLib（几何/UV 正确，截图已确认）」）。
// 之前的草稿只从文件清单/未决/会话标题里凑——那些是**盘点**不是计划，所以只能打 ⬜。
// 这一批是**结构化来源**，因此允许用 🔄 进简报的看板段（这正是那段存在的意义）。
//
// 自动化契约：这些行带 `auto:todos` 模块标记，`syncKanbanAuto` 每次只重写这些行，
// **人写的行一个字节都不动**（与「绝不覆盖」同一条纪律）。

export interface TodoItem { content: string; status: string; updatedAt: number }

const AUTO_MODULE = 'auto:todos'

/** 读 ZCode 里本项目的近期待办。绝不抛：读不到返回 []。 */
export function todoRowsOf(root: string, cfg: RelayConfig, days = 7, limit = 6): TodoItem[] {
  try {
    const p = zcodeDbPath(cfg)
    if (!fs.existsSync(p)) return []
    const z = new Database(p, { readonly: true })
    try {
      // ⚠️ 必须排除子代理/工作流子会话的待办——实测不加这条，抓到的 6 条全是子代理任务书里的
      //    「Submit structured result」「汇总 unclear / unsupported / willAsk」（audit actor 的 todo）。
      //    这跟决策侧同一个教训：**来源比内容更可靠**，而 task_type 就是来源的真值。
      const rows = z.prepare(`
        SELECT t.content AS content, t.status AS status, t.time_updated AS updatedAt
        FROM todo t JOIN session s ON s.id = t.session_id
        WHERE lower(s.directory) = lower(?) AND t.time_updated >= ?
          AND coalesce(s.task_type, '') NOT IN ('subagent_child', 'workflow_child')
        ORDER BY t.time_updated DESC LIMIT 200`).all(path.resolve(root), Date.now() - days * 86400000) as TodoItem[]
      const seen = new Set<string>()
      const out: TodoItem[] = []
      // 进行中优先（简报只读带 🔄/⛔ 的行），同内容去重留最新
      for (const pass of ['in_progress', 'pending']) {
        for (const r of rows) {
          if (r.status !== pass) continue
          const k = String(r.content ?? '').trim()
          if (!k || seen.has(k)) continue
          seen.add(k)
          out.push({ ...r, content: k })
          if (out.length >= limit) return out
        }
      }
      return out
    } finally { try { z.close() } catch { /* 已关闭 */ } }
  } catch { return [] }
}

/** 待办 → 看板行（进行中打 🔄 会被简报读取；待办打 ⬜ 不进简报）。 */
export function renderTodoRows(todos: TodoItem[]): string[][] {
  return todos.map((t) => [
    String(t.content).slice(0, 34),
    t.status === 'in_progress' ? '🔄 进行中' : '⬜ 待办',
    AUTO_MODULE,
    `来自 ZCode 待办（${new Date(t.updatedAt).toISOString().slice(5, 10)}）`,
  ])
}

/** 看板一变，图自己跟上（只动我们生成的那张；人手写的不碰）。返回一句说明，空串=没动。 */
function refreshOwnGraph(root: string, markdown: string): string {
  try {
    const mmdPath = path.join(root, '.sessionrelay', 'board', 'board.mmd')
    if (!fs.existsSync(mmdPath)) return ''
    if (!fs.readFileSync(mmdPath, 'utf8').slice(0, 120).includes('%% generated by srelay kanban graph')) return ''   // 人写的图不碰
    const rows = markdown.split(/\r?\n/).map((l) => l.split('|').map((s) => s.trim()))
      .filter((c) => c.length >= 5 && /^[✅🔄⛔⬜]/u.test(c[2] ?? ''))
    if (!rows.length) return ''
    const next = '%% generated by srelay kanban graph\n' + renderMermaid(rows)
    if (fs.readFileSync(mmdPath, 'utf8') === next) return ''
    fs.writeFileSync(mmdPath, next, 'utf8')
    return ' · 图已同步'
  } catch { return '' }
}

/** 把自动区（模块列 = auto:todos）替换成最新待办；**其余行逐字保留**。 */
export function syncKanbanAuto(root: string, cfg: RelayConfig): { ok: boolean; reason: string; rows: number } {
  const file = path.join(root, 'progress.md')
  if (!fs.existsSync(file)) return { ok: false, reason: '没有 progress.md（先跑 srelay kanban init）', rows: 0 }
  try {
    const todos = todoRowsOf(root, cfg)
    const fresh = renderTodoRows(todos)
    const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/)
    const isSep = (l: string) => /^\|[-\s|:]+\|$/.test(l.trim())
    const isAuto = (l: string) => l.trim().startsWith('|') && l.includes(AUTO_MODULE)
    // 自动行插在**表格末尾**（而不是表头之后）：
    // 实测插在开头会把人写的行挤出简报的 2 个名额（简报只读 🔄/⛔ 且按文件顺序取前 2 行）——
    // 人写的项目级计划优先，自动的细粒度待办排后面。
    const isRow = (l: string) => l.trim().startsWith('|')
    const out: string[] = []
    let dropped = 0
    let lastRowIdx = -1
    for (const l of lines) {
      if (isAuto(l)) { dropped++; continue }
      if (isRow(l)) lastRowIdx = out.length
      out.push(l)
    }
    const at = lastRowIdx >= 0 ? lastRowIdx + 1 : out.length
    out.splice(at, 0, ...fresh.map((r) => '| ' + r.join(' | ') + ' |'))
    const next = out.join('\n')
    const prev = lines.join('\n')
    let graphNote = ''
    if (next === prev) { refreshOwnGraph(root, next); return { ok: true, reason: '无变化', rows: fresh.length } }
    fs.writeFileSync(file, next, 'utf8')
    graphNote = refreshOwnGraph(root, next)
    return { ok: true, reason: `自动区已刷新（旧 ${dropped} 行 → 新 ${fresh.length} 行）${graphNote}`, rows: fresh.length }
  } catch (e) {
    return { ok: false, reason: '刷新失败：' + String((e as Error)?.message ?? e).slice(0, 80), rows: 0 }
  }
}

// ───────────────────── 看板 → 可视化（2026-10-15 夜 · 桥接） ─────────────────────
//
// 用户点名：开源那边有一堆好看的看板/流程图设计，要**桥接进来**而不是只改外观。
// 本机已有的实物参照：D:\agent1super\architecture.mmd —— flowchart TB + subgraph +
//   classDef done/doing 状态着色 + 带标签的边。下面照它的风格生成，保持一致。
//
// 为什么不引第三方库：① 本机离线优先；② Mermaid 是纯文本，编辑器/GitHub/IDE 直接渲染；
//   ③ 「我们的数据 → 图」这一层是独有的（状态与依赖都在 progress.md 里），第三方库解决不了，
//   只会多一个依赖。所以桥接的是**格式与观感**，不是引包。

/** 状态 → Mermaid class（沿用 architecture.mmd 的 classDef 命名）。 */
function statusClass(s: string): string {
  if (/✅/.test(s)) return 'done'
  if (/🔄/.test(s)) return 'doing'
  if (/⛔/.test(s)) return 'blocked'
  return 'todo'
}

/** 行 → 节点 id（稳定可读：行序 + 去标点短名）。 */
function nodeIdOf(name: string, i: number): string {
  const slug = name.replace(/[^0-9A-Za-z\u4e00-\u9fa5]+/g, '').slice(0, 10)
  return 'N' + i + '_' + (slug || 'x')
}

/** progress.md 行 → Mermaid 源码。纯函数，便于测试。 */
export function renderMermaid(rows: string[][]): string {
  const L: string[] = ['flowchart TB']
  // 分两个区：人写的计划（读起来是项目级）/ 自动待办（来自 ZCode todo，细粒度）——
  // 一眼能分清哪块该由人维护、哪块是机器同步过来的。
  const human: string[] = []
  const auto: string[] = []
  const nodes: Array<{ id: string; label: string; cls: string; dep: string }> = []
  let inAuto = false
  rows.forEach((c, i) => {
    const rawName = String(c[1] ?? '').replace(/\*\*/g, '').trim()
    if (!rawName) return
    const status = String(c[2] ?? '').trim()
    const dep = String(c[3] ?? '').trim()
    const short = status.replace(/[✅🔄⛔⬜]\s*/g, '').trim().slice(0, 12)
    const id = nodeIdOf(rawName, i)
    // 标签别切在半个词上：到 22 字就截并补省略号
    const shown = rawName.length > 22 ? rawName.slice(0, 22) + '…' : rawName
    const label = shown + '<br/><small>' + short + '</small>'
    const open = /✅/.test(status) ? '([' : /⛔/.test(status) ? '{{' : /🔄/.test(status) ? '[' : '[/'
    const close = /✅/.test(status) ? '])' : /⛔/.test(status) ? '}}' : /🔄/.test(status) ? ']' : '/]'
    // 模块列 = auto:todos 的行归到自动区（与看板 sync 的约定一致）
    const isAuto = String(c[3] ?? '').trim() === 'auto:todos'
    ;(isAuto ? auto : human).push('        ' + id + open + '"' + label + '"' + close)
    void inAuto
    nodes.push({ id, label: rawName, cls: statusClass(status), dep })
  })
  // 依赖边：依赖列里出现别的行名 → 连边（取最长命中，避免短名误配）
  const edgeLines: string[] = []
  for (const n of nodes) {
    if (!n.dep || n.dep === '—' || n.dep === '-') continue
    // ⚠️ 依赖列常被拿来表示「备注/路径」，实测踩过一次假边：某行依赖写的是
    //   `sessionrelay-src/SessionRelay（真源码 fork…）`，于是跟另一行的名字前缀「SessionRelay」连了线——
    //   而它们之间没有任何依赖关系。规则收紧：带路径分隔符的、或超过 40 字的，一律不当作依赖。
    if (/[\\/]/.test(n.dep) || n.dep.length > 40) continue
    const hit = nodes
      .filter((m) => m.id !== n.id && n.dep.includes(m.label.slice(0, 6)))
      .sort((a, b) => b.label.length - a.label.length)[0]
    if (hit) edgeLines.push('    ' + hit.id + ' --> ' + n.id)
  }
  if (human.length) L.push('    subgraph HUMAN["人写的计划（progress.md）"]', '        direction TB', ...human, '    end')
  if (auto.length) L.push('    subgraph AUTO["自动待办（ZCode todo 同步）"]', '        direction TB', ...auto, '    end')
  L.push(...edgeLines)
  L.push('    classDef done fill:#2e7d32,color:#fff')
  L.push('    classDef doing fill:#f9a825,color:#000')
  L.push('    classDef blocked fill:#c62828,color:#fff')
  L.push('    classDef todo fill:#607d8b,color:#fff')
  for (const cls of ['done', 'doing', 'blocked', 'todo']) {
    const ids = nodes.filter((n) => n.cls === cls).map((n) => n.id)
    if (ids.length) L.push('    class ' + ids.join(',') + ' ' + cls)
  }
  return L.join('\n') + '\n'
}

/** 同一份看板数据 → D2 源码（d2lang 的 DSL）。
 *
 * 为什么多出一种：D2 是单个 Go 二进制，能把 .d2 一键导出 SVG/PNG/PDF/PPTX 且自带主题
 * （d2 --theme 200 --sketch in.d2 out.svg）；Mermaid 则零依赖、编辑器与 GitHub 直接渲染。
 * 两者**输出同一份结构**，谁在场就用谁——这就是「桥接」：我们产结构，渲染交给生态。
 * 本机实测两者都没装，所以 .d2 只是顺手产出（装了的人立刻能用），不引入任何依赖。
 */
export function renderD2(rows: string[][]): string {
  const L: string[] = [
    '# generated by srelay kanban graph（导出示例：d2 --theme 200 in.d2 out.svg）',
    'classes: {',
    '  done:    { style.fill: "#2e7d32"; style.font-color: "#ffffff" }',
    '  doing:   { style.fill: "#f9a825"; style.font-color: "#000000" }',
    '  blocked: { style.fill: "#c62828"; style.font-color: "#ffffff" }',
    '  todo:    { style.fill: "#607d8b"; style.font-color: "#ffffff" }',
    '}',
  ]
  const human: string[] = []
  const auto: string[] = []
  rows.forEach((c, i) => {
    const rawName = String(c[1] ?? '').replace(/[\*\"]/g, '').trim()
    if (!rawName) return
    const status = String(c[2] ?? '').trim()
    const isAuto = String(c[3] ?? '').trim() === 'auto:todos'
    const cls = /✅/.test(status) ? 'done' : /🔄/.test(status) ? 'doing' : /⛔/.test(status) ? 'blocked' : 'todo'
    const line = '  n' + i + ': "' + rawName + '" { class: ' + cls + ' }'
    ;(isAuto ? auto : human).push(line)
  })
  if (human.length) L.push('人写的计划（progress.md）: {', ...human, '}')
  if (auto.length) L.push('自动待办（ZCode todo 同步）: {', ...auto, '}')
  return L.join('\n') + '\n'
}

/** 自包含 HTML：离线也能看（Mermaid 源内联；渲染器两级回退；都没有就显示源码）。 */
export function renderGraphHtml(mermaidSrc: string, title: string): string {
  const safe = mermaidSrc.replace(/<\//g, '<\\/')
  const style = 'body{font:14px/1.6 system-ui,sans-serif;margin:24px;background:#0f1115;color:#e6e6e6}'
    + 'h1{font-size:16px;opacity:.85;font-weight:600}pre{background:#161a20;padding:12px;border-radius:8px;overflow:auto;font-size:12px}'
  const head = '<!doctype html><html lang="zh"><head><meta charset="utf-8"><title>' + title + ' · 看板图</title><style>' + style + '</style></head><body>'
  const h1 = '<h1>' + title + ' · 看板依赖图（srelay kanban graph 生成）</h1>'
  const holder = '<div id="m"></div><details><summary>Mermaid 源码（可复制到任意渲染器）</summary><pre id="s"></pre></details>'
  const store = '<script id="msrc" type="text/plain">' + safe + '</script>'
  const boot = '<script type="module">'
    + 'const SRC=document.getElementById("msrc").textContent;document.getElementById("s").textContent=SRC;'
    + 'const put=(svg)=>{document.getElementById("m").innerHTML=svg};'
    + 'try{const m=await import("./vendor/mermaid.min.js");m.default.initialize({startOnLoad:false,theme:"dark"});put((await m.default.render("g",SRC)).svg)}'
    + 'catch(e){try{const m=await import("https://cdn.jsdelivr.net/npm/mermaid@10/dist/mermaid.esm.min.mjs");m.default.initialize({startOnLoad:false,theme:"dark"});put((await m.default.render("g",SRC)).svg)}'
    + 'catch(e2){document.getElementById("m").innerHTML="<p>渲染器不可用（离线且无 vendor/mermaid.min.js）——粘上面的源码到任意 Mermaid 渲染器即可。</p>"}}'
    + '</script>'
  return head + h1 + holder + store + boot + '</body></html>'
}

/** 读 progress.md 里的看板行（与简报插件同口径：状态列第 3 格、以 ✅🔄⛔⬜ 开头）。 */
export function readKanbanRows(root: string): string[][] {
  const file = path.join(root, 'progress.md')
  if (!fs.existsSync(file)) return []
  return fs.readFileSync(file, 'utf8').split(/\r?\n/)
    .map((l) => l.split('|').map((s) => s.trim()))
    .filter((c) => c.length >= 5 && /^[✅🔄⛔⬜]/u.test(c[2] ?? ''))
}

/** 一键出图 → `<root>/.sessionrelay/board/board.mmd`（唯一主格式）；--html / --d2 按需附加。 */
export function writeKanbanGraph(root: string, opts: { html?: boolean; d2?: boolean; out?: string } = {}):
  { ok: boolean; reason: string; nodes: number; mmd: string; htmlPath?: string } {
  try {
    const rows = readKanbanRows(root)
    if (!rows.length) return { ok: false, reason: 'progress.md 里没有可解析的看板行（状态列要以 ✅🔄⛔⬜ 开头）', nodes: 0, mmd: '' }
    const mmd = renderMermaid(rows)
    // [1015 夜 · 规整] 产物**统一进固定目录** `<root>/.sessionrelay/board/`，每项目一个目录：
    //   ① 不再往项目根目录散文件（实测一轮就有 .mmd/.d2/.html 三份躺根目录）；
    //   ② 与记忆库同住在 .sessionrelay/ 下，天然不进版本库、也不与项目文件混在一起；
    //   ③ **主格式只有一个**：`board.mmd`（Mermaid：纯文本、零依赖、编辑器/GitHub 直接渲染）。
    //      HTML 只是「看图入口」（--html 才出），D2 只是「想导出 SVG/PNG 的人自己装二进制」（--d2 才出）。
    const boardDir = opts.out ? path.dirname(path.resolve(root, opts.out)) : path.join(root, '.sessionrelay', 'board')
    fs.mkdirSync(boardDir, { recursive: true })
    const mmdPath = opts.out ? path.resolve(root, opts.out) : path.join(boardDir, 'board.mmd')
    const SIG = '%% generated by srelay kanban graph'
    if (fs.existsSync(mmdPath)) {
      const head = fs.readFileSync(mmdPath, 'utf8').slice(0, 120)
      if (!head.includes(SIG)) {
        return { ok: false, reason: '已存在 ' + path.basename(mmdPath) + ' 且不是本工具生成的（不覆盖；要覆盖请先改名或加 --out）', nodes: rows.length, mmd }
      }
    }
    fs.writeFileSync(mmdPath, SIG + '\n' + mmd, 'utf8')
    if (opts.d2) { try { fs.writeFileSync(path.join(boardDir, 'board.d2'), renderD2(rows), 'utf8') } catch { /* 可选产物 */ } }
    let htmlPath: string | undefined
    if (opts.html) {
      htmlPath = path.join(boardDir, 'board.html')
      fs.writeFileSync(htmlPath, renderGraphHtml(mmd, path.basename(root)), 'utf8')
    }
    return { ok: true, reason: '已生成 ' + mmdPath + (htmlPath ? ' 与 board.html' : ''), nodes: rows.length, mmd, htmlPath }
  } catch (e) {
    return { ok: false, reason: '生成失败：' + String((e as Error)?.message ?? e).slice(0, 80), nodes: 0, mmd: '' }
  }
}

/** 生成看板初稿。不写盘，纯计算——便于测试与 dry-run。 */
export function renderKanbanDraft(opts: {
  projectName: string;
  recentFiles: Array<{ file: string; sessions: number; decisions: number }>;
  unresolved: Array<{ q: string }>;
  recentSessions: Array<{ title: string; messages: number; at: string }>;
  hasKanbanAwareness?: boolean;
}): string {
  const rows: string[][] = [];
  const today = new Date().toISOString().slice(0, 10);

  // 第 1 行：给人一条明确的"从这里开始写"的占位——不是空模板，是带指令的占位。
  rows.push(['（把真实任务写在这里）', '⬜ 待办', '—', '状态列以 ✅/🔄/⛔/⬜ 开头才会被简报读取；明细写"下一步做什么"']);

  // ⚠️ 下面三行**一律用 ⬜**（而不是 🔄/⛔）——这是 1015 夜实测后改的，别顺手改回去：
  // 简报的看板段只读 🔄/⛔ 的行，且**最多 2 行**。原实现给这三行都打了 🔄/⛔，
  // 于是在一个全新项目上：简报的 2 个看板名额被「近 7 天反复在动的文件」「最近几场会话」
  // 两张**自动盘点**占满，而那一段的本意是「计划/下一步」（b3 实测全库最大盲区，只捕获 3.3%）。
  // 更糟的是内容重复：文件盘点与简报里已有的 `🗂 近 7 天反复在动` 行是同一批文件、同一批数字。
  // 所以：生成物只做**人看的骨架**，状态一律 ⬜（简报不读）；真正的任务由人写成 🔄/⛔。
  if (opts.recentFiles.length) {
    const files = opts.recentFiles.slice(0, 3).map((f) => `${f.file}(${f.sessions}场)`).join('、');
    rows.push(['自动盘点：近 7 天在动的文件', '⬜ 待办', '—',
      `${files}。（这是盘点不是任务——简报的 🗂 行已经会显示同一批文件）`]);
  }

  if (opts.unresolved.length) {
    rows.push(['自动盘点：待拍板的未决问题', '⬜ 待办', '—',
      `${opts.unresolved.length} 条，首条：${String(opts.unresolved[0]?.q ?? '').slice(0, 60)}`]);
  }

  if (opts.recentSessions.length) {
    const s = opts.recentSessions.slice(0, 2).map((x) => `${x.at} ${x.title}`).join('；');
    rows.push(['自动盘点：最近几场会话', '⬜ 待办', '—', s.slice(0, 100)]);
  }

  const head = [
    `# ${opts.projectName} · 进度看板（progress.md）`,
    '',
    `> 生成于 ${today}，由 srelay kanban init 从**已有数据**自动起草（近 7 天的文件 / 未决问题 / 最近会话）。`,
    '> **这份文件此后由人维护**——生成器只在文件不存在时写一次，绝不覆盖。',
    '> 格式：| 任务 | 状态 | 模块 | 明细 |，状态列以 ✅🔄⛔⬜ 开头。',
    '> ⚠️ 只有 **🔄 进行中 / ⛔ 阻塞** 的行会被简报读取（最多 2 行）——请把你真正在做的事写成 🔄，',
    '>    卡住的写成 ⛔；下面几行的 ⬜ 是自动盘点（不是任务），简报**不会**读它们。',
    '',
    '| ' + FILE_COL + ' | 状态 | 模块 | 明细 |',
    '|---|---|---|---|',
  ];
  const body = rows.map((r) => '| ' + r.join(' | ') + ' |');
  return [...head, ...body, ''].join('\n');
}

/** 写看板初稿到 <root>/progress.md。已存在则**绝不覆盖**。 */
export function writeKanbanDraft(root: string, db: DB | null, projectId: string | null): KanbanInitResult {
  const file = path.join(root, 'progress.md');
  if (fs.existsSync(file)) {
    return { path: file, created: false, reason: '已存在 progress.md（自动生成物绝不覆盖人手写的文件）', rows: 0 };
  }
  let recentFiles: Array<{ file: string; sessions: number; decisions: number }> = [];
  let unresolved: Array<{ q: string }> = [];
  let recentSessions: Array<{ title: string; messages: number; at: string }> = [];
  if (db) {
    try {
      const rows = db.prepare(`SELECT files_mentioned, decisions, title, message_count, coalesce(last_event_at, created_at) AS t
        FROM sessions WHERE files_mentioned IS NOT NULL AND files_mentioned != '[]'
          AND coalesce(last_event_at, created_at) >= ? ORDER BY t DESC LIMIT 300`)
        .all(new Date(Date.now() - 7 * 86400000).toISOString()) as Array<{ files_mentioned: string; decisions: string | null; title: string | null; message_count: number; t: string }>;
      const agg = new Map<string, { file: string; sessions: number; decisions: number }>();
      for (const r of rows) {
        let files: string[] = []; let decs = 0;
        try { files = JSON.parse(r.files_mentioned); } catch { continue; }
        try { decs = JSON.parse(r.decisions ?? '[]').length; } catch { decs = 0; }
        for (const f of files) {
          if (typeof f !== 'string' || f.length < 4) continue;
          const cur = agg.get(f) ?? { file: f, sessions: 0, decisions: 0 };
          cur.sessions += 1; cur.decisions += decs; agg.set(f, cur);
        }
      }
      // 泛在文件表**不再本地重写一份**：用 store/db.ts 的 UBIQUITOUS_FILES（与简报侧同源）。
      // 原先这里少列了 README.en.md / settings.json / vitest.config.ts / pnpm-lock.yaml，
      // 于是同一个概念在库内有两套口径——正是悄悄漂移的温床。
      recentFiles = [...agg.values()]
        .filter((x) => !UBIQUITOUS_FILES.has(String(x.file).split('/').pop() ?? ''))
        .filter((x) => x.sessions >= 2)
        .sort((a, b) => b.sessions - a.sessions || b.decisions - a.decisions)
        .slice(0, 3);
      recentSessions = rows.slice(0, 3).map((r) => ({ title: String(r.title ?? '（无标题）').slice(0, 40), messages: r.message_count, at: r.t.slice(0, 10) }));
    } catch { /* 取不到数据就只写占位行 */ }
    if (projectId) { try { unresolved = listUnresolved(db, projectId, 5).map((u) => ({ q: u.q })); } catch { unresolved = []; } }
  }
  const text = renderKanbanDraft({ projectName: path.basename(root), recentFiles, unresolved, recentSessions });
  fs.writeFileSync(file, text, 'utf8');
  const rows = text.split('\n').filter((l) => l.startsWith('| ') && !l.startsWith('| 任务')).length;
  return { path: file, created: true, reason: '已生成看板初稿（此后由人维护，生成器不再动它）', rows };
}
