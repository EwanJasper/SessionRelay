#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
gen_atlas.py —— 项目全资源地图生成器（通用版）。

把项目相关文件按分类逐件列出：`路径` —— 一句话「是什么」。
设计目标（来自实战）：零上下文接手者读一页即可知道「项目有什么、在哪、是什么」。

用法：
    py gen_atlas.py <项目根> [--out <文件>] [--append-section <地图文件>]
                    [--config <json>] [--section-title <标题>] [--max-per-group 12]

配置文件（JSON，可选）——放项目特定规则，避免把项目细节写死在脚本里：
{
  "root_files": ["AGENTS.md", "README.md"],           # 根目录固定清单（按序列）
  "sections": [                                        # 分区（按序）
    {"title": "docs（规格·计划）", "dirs": ["docs"]},
    {"title": "源码", "dirs": ["src"]}
  ],
  "skip_dirs": ["node_modules", ".git", "dist"],       # 额外跳过
  "overrides": {"src/main.py": "入口：命令行解析与调度"},  # 关键件人工短述
  "ext_ok": ["md","py","js","json"],                   # 只列这些扩展名（缺省=常见集合）
  "collapse_md_over": 60                               # .md 超过此数才折叠
}

零依赖（仅标准库）。
"""
import argparse
import json
import os
import re
import sys
from datetime import date

DEFAULT_SKIP = {
    'node_modules', '.git', 'dist', 'build', '.venv', 'venv', '__pycache__',
    '.tmp', 'tmp', 'cache', '.cache', 'coverage', '.next', '.nuxt', 'out',
    # 会话/运行产物（噪声：接手者不需要看，且数量极大）
    '.pytest_cache', '.mypy_cache', '.ruff_cache', 'target', 'vendor',
}
# 目录名**模式**跳过（前缀/正则）——比枚举更耐新产物
DEFAULT_SKIP_RE = r'^([.]|session-|_session|.*-profile|playwright)'   # 点目录整体跳过（会话/工具缓存多在此）
DEFAULT_EXT = {
    'md', 'txt', 'json', 'jsonl', 'yaml', 'yml', 'toml', 'ini', 'cfg',
    'py', 'js', 'mjs', 'cjs', 'ts', 'tsx', 'jsx', 'sh', 'ps1', 'bat', 'cmd',
    'sql', 'db', 'csv', 'log', 'out', 'html', 'css',
}
LANG_WORDS = re.compile(r'^(shell|bash|node|python|powershell|sh|zsh)$', re.I)


def headline(path, overrides, max_len=110):
    """抽一句话：override 优先，否则文件首个实义行。"""
    rel = path.replace('\\', '/')
    if rel in overrides:
        return overrides[rel]
    try:
        with open(path, 'r', encoding='utf-8', errors='ignore') as f:
            head = f.read(4096)
    except Exception:
        return '（不可读/二进制）'
    for raw in head.split('\n')[:30]:
        s = raw.strip()
        s = re.sub(r'^#+\s*', '', s)
        s = re.sub(r'^/\*+\s*', '', s)
        s = re.sub(r'^\*\s?', '', s)
        s = re.sub(r'^//\s?', '', s)
        s = re.sub(r'\*/\s*$', '', s).strip()
        if len(s) < 6:
            continue
        if re.match(r'^["\']use strict["\']', s):
            continue
        if s in ('---', '"""', "'''"):
            continue
        if LANG_WORDS.match(s):
            continue
        if s.startswith('#'):
            continue
        # 过滤：HTML 注释 / 纯符号行 / JSON 片段 / 生成器标记
        if s.startswith('<!--') or s.startswith('-->') or s.endswith('-->'):
            continue
        if re.match(r'^[\[\{\}\)\]<>=\-*_~`|/\\:;,.!?\'"+]+$', s):
            continue
        if re.match(r'^["\']?\w+["\']?\s*:\s*', s) and s.rstrip().endswith((',', '{', '}')):
            continue
        if 'dsh-openwolf' in s or 'generated by' in s.lower():
            continue
        # 需含至少一个「词」字符（中英文/数字），排除纯标点
        if not re.search(r'[0-9A-Za-z\u4e00-\u9fff]', s):
            continue
        return s if len(s) <= max_len else s[:max_len - 2] + '…'
    return '（无一句话可抽）'


def walk(root, subdir, skip_dirs, ext_ok, skip_files_re, skip_dir_re=None):
    out = []
    base = os.path.join(root, subdir) if subdir else root
    if not os.path.isdir(base):
        return out
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(
            d for d in dirnames
            if d not in skip_dirs and not (skip_dir_re and skip_dir_re.match(d)))
        for fn in sorted(filenames):
            if skip_files_re and skip_files_re.search(fn):
                continue
            ext = os.path.splitext(fn)[1].lstrip('.').lower()
            if ext not in ext_ok:
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root).replace('\\', '/')
            out.append((rel, full))
    return out


def emit(title, items, root, overrides, collapse_over, collapse_md_over):
    md = []
    md.append('### %s（%d）' % (title, len(items)))
    md.append('')
    groups, collapsed = {}, set()
    for rel, full in items:
        d = os.path.dirname(rel) or '.'
        ext = os.path.splitext(rel)[1].lstrip('.').lower()
        key = (d, 'md' if ext == 'md' else 'other')
        groups.setdefault(key, []).append((rel, full))
    for (d, kind), g in groups.items():
        if len(g) <= collapse_over:
            continue
        if kind == 'md' and len(g) <= collapse_md_over:
            continue
        sample = g[0]
        for rel, _ in g:
            collapsed.add(rel)
        md.append('- `%s/`（%d 件）—— 代表件 `%s`：%s'
                  % (d, len(g), os.path.basename(sample[0]), headline(sample[1], overrides)))
    for rel, full in items:
        if rel in collapsed:
            continue
        md.append('- `%s` —— %s' % (rel, headline(full, overrides)))
    md.append('')
    return md


def check_atlas(root, mapfile):
    """地图腐烂检测：地图是**追加式**的，旧节引用的文件会随时间消失。
    只审不写——把地图里的 `路径` 逐条找回，报「地图里写了、盘上没有了」。"""
    import re as _re
    if not os.path.isfile(mapfile):
        print("[gen_atlas] 地图文件不存在: %s" % mapfile); return 2
    text = open(mapfile, encoding="utf-8").read()
    # 只认「- `path` —— 什么」这种文件全图条目，以及代码块外的反引号路径
    cands = set()
    for m in _re.finditer(r"^- `([^`]+)`\s*——", text, _re.M):
        cands.add(m.group(1).strip())
    # 只认「- `path` —— 什么」这种条目。v1.1 实测：全文扫反引号会把 `.md``>=22.5``Corr=0.961`
    # 这类非路径 token 全抓进来，一次报 71 条"腐烂"里大半是噪声 ⇒ 审计不可用。
    skipped = 0
    stale, ok, ext = [], 0, 0
    # basename 索引只建一次（原来每条缺失都 os.walk 一遍整棵树，大项目上会慢到不可用）
    index = {}
    for dp, dns, fns in os.walk(root):
        for fn in fns:
            index.setdefault(fn, os.path.join(dp, fn))
    for c in sorted(cands):
        c2 = c.replace("\\", "/")
        # 模板/占位/通配/无扩展名 —— 不是可判定路径，跳过（与 anchor_audit 同一套口径纪律）
        if (c2.startswith("http") or "…" in c2 or c2.endswith("/") or "%" in c2
                or any(ch in c2 for ch in "*<>{}")
                or not _re.search(r"\.[A-Za-z0-9]{1,6}$", c2)):
            skipped += 1
            continue
        full = c2 if os.path.isabs(c2) else os.path.join(root, c2)
        if os.path.exists(full):
            ok += 1
        else:
            # 兜底：按 basename 在项目里找（地图里常写简写）
            base = os.path.basename(c2)
            found = index.get(base)
            if found:
                ext += 1
            else:
                stale.append(c)
    print("[gen_atlas] 地图腐烂检测: %s" % mapfile)
    print("  文件条目 %d ｜ 路径命中 %d ｜ 靠 basename 兜底命中 %d ｜ 腐烂 %d ｜ 模板/通配跳过 %d"
          % (len(cands), ok, ext, len(stale), skipped))
    for c in stale[:40]:
        print("  ❌ 地图里写了、盘上没有了: %s" % c)
    if len(stale) > 40:
        print("  ...（其余 %d 条省略）" % (len(stale) - 40))
    if not stale:
        print("  ✅ 无腐烂引用")
    return 0 if not stale else 1

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('root')
    ap.add_argument('--out', default=None)
    ap.add_argument('--append-section', default=None, help='把结果作为新节追加到该地图文件（不改旧节）')
    ap.add_argument('--config', default=None)
    ap.add_argument('--section-title', default=None)
    ap.add_argument('--max-per-group', type=int, default=12)
    ap.add_argument('--check', default=None, help='只审不写：检查该地图文件里引用的路径是否还在盘上（地图腐烂检测）')
    a = ap.parse_args()
    if a.check:
        return check_atlas(os.path.abspath(a.root), a.check)

    root = os.path.abspath(a.root)
    cfg = {}
    if a.config and os.path.isfile(a.config):
        with open(a.config, encoding='utf-8') as f:
            cfg = json.load(f)

    skip_dirs = DEFAULT_SKIP | set(cfg.get('skip_dirs', []))
    ext_ok = set(cfg.get('ext_ok', [])) or DEFAULT_EXT
    overrides = cfg.get('overrides', {})
    skip_files_re = re.compile(cfg['skip_files_regex']) if cfg.get('skip_files_regex') else None
    skip_dir_re = re.compile(cfg.get('skip_dir_regex') or DEFAULT_SKIP_RE)
    sections = cfg.get('sections') or [{'title': '全部文件', 'dirs': ['']}]

    md = []
    title = a.section_title or ('文件全图（%s · 生成器产出，勿手改）' % date.today().isoformat())
    md.append('## ' + title)
    md.append('')
    md.append('> 生成：`py gen_atlas.py %s`；跳过依赖/构建/媒体目录；每行＝路径 ＋ 一句话「是什么」。' % root)
    md.append('')

    # 根目录固定清单
    root_files = [f for f in cfg.get('root_files', []) if os.path.isfile(os.path.join(root, f))]
    if root_files:
        md.append('### 根目录（%d）' % len(root_files))
        md.append('')
        for f in root_files:
            md.append('- `%s` —— %s' % (f, headline(os.path.join(root, f), overrides)))
        md.append('')

    total = 0
    for sec in sections:
        items = []
        for d in sec.get('dirs', []):
            items += walk(root, d, skip_dirs, ext_ok, skip_files_re, skip_dir_re)
        if not items:
            continue
        md += emit(sec['title'], items, root, overrides, a.max_per_group,
                   cfg.get('collapse_md_over', 60))
        total += len(items)

    md.append('（生成完 · %s · 共 %d 件在列）' % (date.today().isoformat(), total))
    text = '\n'.join(md)

    if a.append_section:
        p = a.append_section
        old = open(p, encoding='utf-8').read() if os.path.isfile(p) else ''
        with open(p, 'w', encoding='utf-8') as f:
            f.write(old.rstrip('\n') + '\n\n' + text + '\n')
        print('[gen_atlas] 已追加新节到 %s（%d 件在列，旧节未改）' % (p, total))
    elif a.out:
        with open(a.out, 'w', encoding='utf-8') as f:
            f.write(text + '\n')
        print('[gen_atlas] -> %s（%d 件在列）' % (a.out, total))
    else:
        print(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
